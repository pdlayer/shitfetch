void
sfmini_palette_for_os(const char *os_id, const char *out[9])
{
	size_t i;
	size_t j;
	const char *match = os_id;

	if (match == NULL || match[0] == '\0')
		match = "linux";
	for (i = 0; i < sizeof(sfmini_palettes) / sizeof(sfmini_palettes[0]); i++) {
		if (strcmp(sfmini_palettes[i].name, match) == 0) {
			for (j = 0; j < 9; j++)
				out[j] = sfmini_palettes[i].colors[j];
			return;
		}
	}
	for (j = 0; j < 9; j++)
		out[j] = sfmini_default[j];
}
