static bool
is_numeric_color(const char *s)
{
	size_t i;

	if (s == NULL || s[0] == '\0')
		return false;
	for (i = 0; s[i] != '\0'; i++) {
		if (!isdigit((unsigned char)s[i]) && s[i] != ';')
			return false;
	}
	return true;
}

static bool
parse_hex_color(const char *s, char *out, size_t out_cap)
{
	unsigned int r, g, b;

	if (s == NULL || s[0] != '#' || strlen(s) != 7)
		return false;
	if (sscanf(s + 1, "%02x%02x%02x", &r, &g, &b) != 3)
		return false;
	snprintf(out, out_cap, "38;2;%u;%u;%u", r, g, b);
	return true;
}

bool
sfcolor_resolve(const char *spec, const char *logo_color, char *out, size_t out_cap)
{
	char lower[64];
	size_t i;

	if (out == NULL || out_cap == 0)
		return false;
	out[0] = '\0';
	if (spec == NULL || spec[0] == '\0')
		return false;

	if (is_numeric_color(spec)) {
		snprintf(out, out_cap, "%s", spec);
		return true;
	}
	if (parse_hex_color(spec, out, out_cap))
		return true;

	snprintf(lower, sizeof(lower), "%s", spec);
	for (i = 0; lower[i] != '\0'; i++) {
		lower[i] = (char)tolower((unsigned char)lower[i]);
		if (lower[i] == '_')
			lower[i] = '-';
	}
	if (strcmp(lower, "logo") == 0 || strcmp(lower, "main") == 0) {
		if (logo_color != NULL && logo_color[0] != '\0') {
			snprintf(out, out_cap, "%s", logo_color);
			return true;
		}
		return false;
	}

	for (i = 0; i < sizeof(sfcolor_named) / sizeof(sfcolor_named[0]); i++) {
		if (strcmp(lower, sfcolor_named[i].name) == 0) {
			snprintf(out, out_cap, "%s", sfcolor_named[i].code);
			return true;
		}
	}
	return false;
}
